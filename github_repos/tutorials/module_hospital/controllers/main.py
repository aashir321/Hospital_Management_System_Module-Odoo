from odoo import http  # pyright: ignore[reportMissingImports]
from odoo.http import request  # pyright: ignore[reportMissingImports]

import io
import xlsxwriter
from datetime import datetime


class PatientExcel(http.Controller):

    @http.route('/patient/excel/<int:patient_id>', type='http', auth='user')
    def patient_excel(self, patient_id, **kwargs):

        patient = request.env['hospital.patients'].sudo().browse(patient_id)

        output = io.BytesIO()
        workbook = xlsxwriter.Workbook(output, {'in_memory': True})
        sheet = workbook.add_worksheet("Patient Report")

        # --------------------------
        # Workbook Settings
        # --------------------------

        sheet.set_landscape()
        sheet.fit_to_pages(1, 0)
        sheet.freeze_panes(6, 0)
        sheet.set_zoom(110)

        sheet.set_column('A:A', 30)
        sheet.set_column('B:B', 40)

        # --------------------------
        # Formats
        # --------------------------

        title = workbook.add_format({
            'bold': True,
            'font_size': 18,
            'align': 'center',
            'valign': 'vcenter',
            'bg_color': '#1F4E78',
            'font_color': 'white',
            'border': 1
        })

        subtitle = workbook.add_format({
            'bold': True,
            'font_size': 12,
            'align': 'center',
            'border': 1,
            'bg_color': '#D9EAD3'
        })

        info = workbook.add_format({
            'italic': True,
            'font_size': 10
        })

        label = workbook.add_format({
            'bold': True,
            'bg_color': '#D9EAD3',
            'border': 1,
            'align': 'left',
            'valign': 'vcenter'
        })

        value = workbook.add_format({
            'border': 1,
            'align': 'left'
        })

        money = workbook.add_format({
            'border': 1,
            'num_format': '#,##0.00'
        })

        total = workbook.add_format({
            'bold': True,
            'border': 1,
            'bg_color': '#FFF2CC',
            'num_format': '#,##0.00'
        })

        date_format = workbook.add_format({
            'border': 1,
            'num_format': 'dd-mmm-yyyy'
        })

        # --------------------------
        # Header
        # --------------------------

        sheet.merge_range('A1:B1', 'ABC HOSPITAL', title)
        sheet.merge_range('A2:B2', 'Patient Information Report', subtitle)

        sheet.write('A4', 'Generated By:', label)
        sheet.write('B4', request.env.user.name, value)

        sheet.write('A5', 'Generated On:', label)
        sheet.write(
            'B5',
            datetime.now().strftime('%d-%b-%Y %I:%M %p'),
            value
        )
        sheet.insert_image(
            'A1',
            '/mnt/extra-addons/github_repos/tutorials/module_hospital/static/src/img/logo.png',
            {'x_scale': 0.4, 'y_scale': 0.4}
        )

        # --------------------------
        # Patient Data
        # --------------------------

        row = 7

        def write(label_text, value_text, fmt=value):
            nonlocal row
            sheet.write(row, 0, label_text, label)
            sheet.write(row, 1, value_text if value_text else "", fmt)
            row += 1

        write("Patient Name", patient.name)
        write("Blood Group", dict(patient._fields['blood_group'].selection).get(patient.blood_group, ""))
        write("Age", patient.age)
        write("Date of Birth", str(patient.date_of_birth or ""))
        write("Gender", dict(patient._fields['gender'].selection).get(patient.gender, ""))
        write("Email", patient.email)
        write("Phone", patient.phone)
        write("Address", patient.address)
        write("Medical History", patient.medical_history)
        write("Guardian", patient.emergency_contact_name)
        write("Relationship", patient.emergency_contact_relationship)
        write("Emergency Phone", patient.emergency_contact_phone)

        sheet.write(row, 0, "Consultation Fee", label)
        sheet.write_number(row, 1, patient.consultation_fee or 0, money)
        row += 1

        sheet.write(row, 0, "Medicine Charges", label)
        sheet.write_number(row, 1, patient.medicine_charges or 0, money)
        row += 1

        sheet.write(row, 0, "Tax", label)
        sheet.write_number(row, 1, patient.tax_amount or 0, money)
        row += 1

        sheet.write(row, 0, "Discount", label)
        sheet.write_number(row, 1, patient.discount_amount or 0, money)
        row += 1

        sheet.write(row, 0, "Grand Total", label)
        sheet.write_number(row, 1, patient.grand_total or 0, total)

        # --------------------------
        # Footer
        # --------------------------

        sheet.set_footer(
            '&LGenerated from Odoo ERP&CPatient Report&RPage &P of &N'
        )

        workbook.close()

        output.seek(0)

        filename = "Patient_%s.xlsx" % (patient.name or "Report")

        return request.make_response(
            output.read(),
            headers=[
                (
                    'Content-Type',
                    'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet'
                ),
                (
                    'Content-Disposition',
                    'attachment; filename="%s"' % filename
                ),
            ]
        )